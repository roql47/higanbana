/** 증거는 마지막 대사 뒤에만 확정한다. 중간 종료는 같은 기록부터 재개하며 이중 실행을 막는다. */
export class TruthReconstruction {
  private playing = false;
  get busy() { return this.playing; }
  get next() { return TRUTH_RECORDS.findIndex((record) => !this.evidence.has(record.id)); }
  get complete() { return this.next === -1; }
  constructor(
    private evidence: ReadonlySet<string>,
    private dialogue: Pick<Dialogue, 'say' | 'choose'>,
    private remember: (id: string) => unknown,
  ) {}
  async read(index: number): Promise<boolean> {
    if (this.playing || index !== this.next || index < 0 || index >= TRUTH_RECORDS.length) return false;
    const record = TRUTH_RECORDS[index]!;
    this.playing = true;
    try {
      await this.dialogue.say(...record.opening);
      const choice = await this.dialogue.choose(L('기억에서 무엇을 확인할까?', '記憶の何を確かめる？'), record.options);
      if (choice !== 0 && choice !== 1) return false;
      await this.dialogue.say(...record.focus[choice],
        ...(this.evidence.has('manor:dispatch-unlocked') && record.id === 'truth:well'
          ? [mio('회신함은 확인 대기였어. 소리가 났는데도 확인을 끝내지 않은 채 사람들을 돌린 거야.', '返信箱は確認待ちだった。音がしていたのに、確認を終えないまま人を向け直したんだ。')]
          : []),
        ...(this.evidence.has('manor:dispatch-unlocked') && record.id === 'truth:villagers'
          ? [mio('같은 인장이었어. 생존자를 확인하라는 말도, 나를 데려오라는 말도 이 집에서 찍었어.', '同じ印だった。生存者を確かめろという言葉も、私を連れてこいという言葉も、この家で押された。'),
            mio('꾸러미에는 사람을 구해 달라는 부탁이 남았어. 그 부탁을 두고 무엇을 먼저 하기로 했는지, 이제 보이네.', '包みには人を助けてほしいという頼みが残ってた。それを置いて何を先にすると決めたのか、今なら見える。')]
          : []),
        ...(record.id === 'truth:villagers' && this.evidence.has('case:manor:complete')
          ? [mio('두 명령서의 순서도 확인했어. 피해 보고가 오기 전에 구조 인원을 나를 찾는 쪽으로 돌렸어.', '二つの命令の順も確かめた。被害報告が来る前に、救助の人を私の捜索へ回した。'),
            mio('지금 본 기억만이 아니야. 그들이 남긴 문서에도 같은 선택이 남아 있어.', '今見た記憶だけじゃない。彼らが残した文書にも同じ選択が残っている。')]
          : []), ...record.closing);
      this.remember(`${record.id}:focus-${choice}`);
      this.remember(record.id);
      return true;
    } finally { this.playing = false; }
  }
}
